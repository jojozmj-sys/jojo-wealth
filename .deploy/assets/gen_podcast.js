function stripTags(s) {
  return String(s == null ? '' : s)
    .replace(/<!\[CDATA\[(.*?)\]\]>/gs, '$1')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// 把 RSS 简介清洗成可读的解读型导语：
//  - 去掉方括号/花括号包裹的流水账（制作人/嘉宾/广告等）
//  - 去掉主持人自我介绍、出品/赞助/收听引导等行
//  - 去掉纯 emoji/符号行，压缩成一段像"解读"的导语
function cleanDesc(raw) {
  let s = String(raw == null ? '' : raw)
    .replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&nbsp;/g, ' ')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#\d+;/g, '')
    // 去掉【...】、[...]、{...}、(...) 括号内流水账
    .replace(/【[^】]*】/g, ' ')
    .replace(/\[[^\]]*\]/g, ' ')
    .replace(/\{[^}]*\}/g, ' ')
    .replace(/（[^）]*）?/g, ' ')
    // 去掉常见引导前缀
    .replace(/^(本期|本期节目)?(制作人|嘉宾|主播|主持人|导语)[：:].*?。?/g, ' ')
    .replace(/^(我是|大家好，我是|欢迎收听|感谢.{0,6}收听)[^。]*。?/g, ' ')
    .replace(/^(本期|这一期|这期)?节目?(将)?/g, ' ')
    .replace(/^[-\s—]+导语[-\s—]*/g, ' ');
  // 按句切分
  const lines = s.split(/[\n。；]/)
    .map(x => x.trim())
    .filter(x => x.length >= 6);
  const bad = /出品|赞助|由.{0,8}制作|制作人|嘉宾|主播|制片|主持|欢迎收听|收听|关注公众号|小宇宙|喜马拉雅|时间线|timeline|本节目由|广告|独家|哔哩哔哩|一键三连|听友|微博|微信|订阅|推广|合作|版权|侵删|🫧|🚀/i;
  const kept = [];
  for (const l of lines) {
    if (/^[^\u4e00-\u9fa5a-zA-Z0-9]{3,}$/.test(l)) continue; // 纯符号/emoji 行
    if (bad.test(l)) continue;
    if (/^(我是|大家好|本期|你们好|嗨|哈喽|hello|hi)[，,：:\s]/.test(l)) continue; // 开场白
    kept.push(l);
  }
  // 拼接，最多保留 ~150 字作为解读导语
  let out = kept.join('。').replace(/[。]+/g, '。').replace(/^[\s。，,、]+/, '');
  return out.slice(0, 150);
}

