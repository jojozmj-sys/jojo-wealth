// 从简介里尽力提取「当期重要语句」（带引号/书名号提示的句子），并过滤杂质：
//  - 剔除太短（<8字）或超长（>58字）的碎片
//  - 剔除含时间戳(12:34)、节目名、赞助/出品/本节目/分钟/部分/章节等噪声词的行
//  - 剔除纯英文拼接、以「第/二/三/四/五…部分」开头的章节标题
//  - 目标至少 5 句：先从简介抓，不足再补节目定位里的常青金句
function extractQuotes(name, d) {
  const quotes = [];
  const NOISE = new RegExp(
    (name || '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
    '|\\d{1,2}:\\d{2}|节目|出品|赞助|本节目|制作|收听|欢迎|时间线|分钟|部分|章节|——请|注：|抱歉|补充|改口|第[一二三四五六七八九十百千]+(部分|章|回)' +
    '|leftright|rightleft|微博|微信|公众号|抖音|B站|小红书', 'i');
  const m = d ? d.match(/[“「『"][^”」』"]{8,60}[”」』"]/g) : null;
  if (m) {
    for (const raw of m) {
      const q = raw.trim().replace(/^[“「『"]/, '“').replace(/[”」』"]$/, '”');
      if (q.length < 8 || q.length > 58) continue;
      if (NOISE.test(q)) continue;
      if (/^[“\u201C][A-Za-z\s]{4,}[”\u201D]$/.test(q)) continue; // 纯英文拼接
      quotes.push(q);
      if (quotes.length >= 5) break;
    }
  }
  // 若简介里没抓够 5 句合格引语，则补节目定位里的常青金句（保证每期至少 5 句重要语句）
  const lib = INSIGHT_LIB[name];
  if (lib && lib.quotes) {
    for (const q of lib.quotes) {
      if (quotes.length >= 5) break;
      if (!quotes.includes(q)) quotes.push(q);
    }
  }
  return quotes.slice(0, 8); // 上限 8 句，避免过长
}

// 为最新一期生成「深度完整解读」：
//  - core    : 当期主题一句话点题（结合 RSS 标题）
//  - points  : 本期值得展开的 2-3 个看点（基于节目定位 + 简介关键句）
//  - reason  : 为什么这期值得听（节目定位提炼）
//  - quotes  : 当期重要语句（至少 5 句）
//  - full    : 多段落深度解读（参考精选深度解读的完整内容结构，结合节目框架 + 当期主题）
function buildInsight(name, ep) {
  const t = (ep.title || '').trim();
  const d = ep.desc || '';
  const lib = INSIGHT_LIB[name] || {};
  const angle = lib.angle || '一档值得关注的播客';
  const points = lib.points ? lib.points.slice() : [];
  const reason = lib.reason || `延续《${name}》一贯的内容水准，值得点开收听完整内容。`;

  // 从 RSS 标题提炼「主题短句」（去节目号/栏目前缀，取真正的话题部分）
  let theme = t.replace(/^[^：:]*[：:]/, '')       // 去「No.80：」这类前缀
               .replace(/^(S\d+E\d+|EP?\s*\d+|Vol\.?\s*\d+|vol\.?\s*\d+|No\.?\s*\d+)\s*[：:·|\s]\s*/i, '')  // 去 EP245 / No.81 编号
               .replace(/^(第?\d+(期|集|回|章)?)\s*[：:·|\s]\s*/, '')  // 去「第x期」编号
               .replace(/[|｜\s【】\[\]·—\-]+$/, '')
               .replace(/^[|｜\s【】\[\]·—\-]+/, '')
               .trim()
               .slice(0, 36);
  if (!theme) theme = t.slice(0, 36);

  const core = `本期《${name}》围绕「${theme}」展开。${angle}，延续节目一贯的深度与质感。`;
  // 若简介里有实质内容，追加一句简介关键句作为「当期要点」
  const intro = cleanDesc(d);
  const extra = intro && intro.length > 20 && !/这是《/.test(intro)
    ? intro.split('。').slice(0, 2).join('。').slice(0, 120)
    : '';
  const p2 = extra ? `当期重点：${extra.replace(/[。]+$/, '')}。` : `当期具体展开仍以完整音频为准，以上为节目定位下的解读框架。`;
  if (points.length > 1) points[1] = points[1].replace(/[。]+$/, '') + '。' + p2; else points.push(p2);

  // 生成多段落深度解读 full（参考精选深度解读的结构：开场→核心方法论→当期切入→为什么值得听→结尾）
  let full = '';
  if (lib.full) {
    // 在节目框架的【开场】段中融入当期主题
    full = lib.full.replace(
      /【开场】\n/,
      `【开场】\n本期主题：「${theme}」。`
    );
  } else {
    // 兜底：用 core + points + reason 拼一段完整解读
    full = `【开场】\n本期主题：「${theme}」。${core}\n\n【核心看点】\n${points.map(p => '• ' + p).join('\n')}\n\n【为什么值得听】\n${reason}\n\n【结尾】\n延续《${name}》一贯的内容水准，值得点开收听完整内容。`;
  }

  return { core, points, reason, quotes: extractQuotes(name, d), full };
}

// 抓取单个播客 RSS 的最新一期
async function fetchLatestEpisode(name, feedUrl) {
  try {
    const r = await fetch(feedUrl, {
      signal: AbortSignal.timeout(15000),
      headers: { 'User-Agent': UA }
    });
    const txt = await r.text();
    const items = txt.match(/<item>[\s\S]*?<\/item>/g) || [];
    if (!items.length) return null;
    const it = items[0];
    const g = (pat) => { const m = it.match(pat); return m ? stripTags(m[1]) : ''; };
    const title = g(/<title>(.*?)<\/title>/);
    const desc = g(/<description>(.*?)<\/description>/);
    const pub = g(/<pubDate>(.*?)<\/pubDate>/);
    const link = g(/<link>(.*?)<\/link>/);
    if (!title) return null;
    const ep = {
      show: name,
      title: title.slice(0, 120),
      desc: desc ? desc.slice(0, 300) : '',
      pub: pub,
      link: link && link.startsWith('http') ? link : ''
    };
    // 新增：深度完整解读（core 主题点题 / points 看点 / reason 值得听理由 / quotes 当期重要语句 / full 多段落深度解读）
    const ins = buildInsight(name, { title: ep.title, desc: desc });
    ep.core = ins.core;
    ep.points = ins.points;
    ep.reason = ins.reason;
    ep.quotes = ins.quotes;
    ep.full = ins.full;
    // 本期解读摘要（供「热门播客·最新一期」版块直接展示）
    ep.insight = ins.core;
    return ep;
  } catch (e) {
    console.error(`[${name}] RSS抓取失败:`, e.message);
    return null;
  }
}

// 并行抓取所有播客最新一期，按固定节目顺序输出，失败的跳过
async function fetchPodcastLatest() {
  const entries = Object.entries(PODCAST_RSS);
  const results = await Promise.all(entries.map(([name, url]) => fetchLatestEpisode(name, url)));
  return entries.map(([name], i) => results[i]).filter(Boolean);
}

