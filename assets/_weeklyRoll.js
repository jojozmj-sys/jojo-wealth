const CATEGORIES = ['人物描写','环境描写','动作描写','心理描写','细节描写','抒情','议论','对话'];

// 4. 选段函数：去重 + 分类均衡
function pickWeek(weekNum, isLongPool = false) {
  // 8 分类，每个分类 2 篇短（短池 7 天 × 5 = 35；长池 7 天 × 2 = 14）
  // 短池一周 35-50 篇；长池一周 14-16 篇
  const daysCount = isLongPool ? 7 : 7;  // 一周 7 天
  const perDayShort = isLongPool ? 0 : 5;  // 短池每天 5 篇（3 短 + 2 长，实际由 app 分配）
  const perDayLong = isLongPool ? 2 : 0;   // 长池每天 2 篇

  // 短池 35 篇 = 7 天 × 5 篇；8 分类均匀分布 (约 4-5 篇/分类)
  // 长池 14 篇 = 7 天 × 2 篇；8 分类各 1.75 → 1-2 篇/分类
  const distribution = isLongPool
    ? [2,2,2,2,2,2,1,1]   // 长池 14
    : [5,5,4,4,4,4,5,4];   // 短池 35

  const result = [];
  let dayIdx = 0;
  for (let cIdx = 0; cIdx < CATEGORIES.length; cIdx++) {
    const cat = CATEGORIES[cIdx];
    const need = distribution[cIdx];
    const candidates = [];

    // 收集该分类下所有未用过的 (作者, 篇目) 组合
    for (const [author, byCat] of Object.entries(CANDIDATES)) {
      if (!byCat[cat]) continue;
      for (const ti of byCat[cat]) {
        const key = `${author}::${ti}`;
        if (used.has(key)) continue;
        candidates.push({ author, ti, key });
      }
    }

    // 打乱候选
    for (let i = candidates.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [candidates[i], candidates[j]] = [candidates[j], candidates[i]];
    }

    for (let i = 0; i < need && i < candidates.length; i++) {
      const c = candidates[i];
      result.push({
        category: cat,
        source: `${c.author}·${c.ti}`,
        passage: `[待填充：新一周内容，请基于${c.author}${c.ti}的${cat}选一段]`,
        analysis: `[待填充]`,
        prompt: `[待填充]`
      });
      used.add(c.key);
    }
  }

  return result;
}

